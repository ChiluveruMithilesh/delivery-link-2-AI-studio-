export function lookupShopkeeperByCode(code: string): RegisteredShop | undefined {
  if (!code) return undefined;
  const cleanCode = code.trim().toUpperCase();
  return REGISTERED_SHOPS.find((s) => s.code.toUpperCase() === cleanCode);
}

export function searchShopkeepers(query: string): RegisteredShop[] {
  if (!query || query.trim() === '') return REGISTERED_SHOPS.slice(0, 10);
  const q = query.trim().toLowerCase();
  return REGISTERED_SHOPS.filter(
    (s) =>
      s.code.toLowerCase().includes(q) ||
      s.shopName.toLowerCase().includes(q) ||
      s.ownerName.toLowerCase().includes(q) ||
      s.locality.toLowerCase().includes(q) ||
      s.phone.replace(/[\s+-]/g, '').includes(q.replace(/[\s+-]/g, ''))
  );
}
